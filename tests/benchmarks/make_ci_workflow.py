#!/usr/bin/env python3
"""
Generate a CI workflow that replays each accepted fix's PoV on every commit.

    python -m tests.benchmarks.make_ci_workflow RUN_ID [--out .github/workflows/kavach-pov-replay.yml]

For every target in the run whose patch was accepted with the PoV gate PASSED,
the workflow rebuilds the target (with the sanitizer build the benchmark used)
and runs its PoV. A later commit that re-introduces the bug makes the PoV
reproduce again and the job fail.

Scope, stated plainly: it replays the PoV against the source files as they are
in the repository at that commit. It does not apply the patch from the run; the
fix has to have been committed for the job to be green. Targets whose sources
live outside the repository (the real-CVE worktrees under benchmark_workspace/)
are skipped and listed in a comment at the top of the generated file.
"""

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

from tests.benchmarks.targets import get_suite                                  # noqa: E402
from src.patch_validator.drv_loop import DRVLoop                                 # noqa: E402

RUNS = ROOT / "reports" / "benchmark_runs"


def accepted_with_pov(run_dir: Path) -> list[str]:
    with open(run_dir / "per_target_results.csv", newline="") as f:
        return [r["ID"] for r in csv.DictReader(f)
                if r["Status"] == "patched" and r.get("PoV_Gate") == "pass"]


def step_for(t) -> str:
    rel = Path(t.file_path)
    ctx = {"src": f"$GITHUB_WORKSPACE/{rel.as_posix()}",
           "srcdir": f"$GITHUB_WORKSPACE/{rel.parent.as_posix()}",
           "bin": "$RUNNER_TEMP/" + t.id, "workspace": "$RUNNER_TEMP"}
    build = DRVLoop.expand(t.build_command, ctx).replace(str(ROOT), "$GITHUB_WORKSPACE")
    pov = DRVLoop.expand(t.pov_command, ctx).replace(str(ROOT), "$GITHUB_WORKSPACE")
    script = f"set -e\n{build}\n{pov}\n"
    body = "\n".join("          " + line for line in script.splitlines())
    return (f"      - name: PoV replay {t.id}\n"
            f"        shell: bash\n"
            f"        run: |\n{body}\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--out", default=str(ROOT / "reports" / "ci" / "kavach-pov-replay.yml"))
    args = ap.parse_args()
    run_dir = Path(args.run) if Path(args.run).is_dir() else RUNS / args.run
    ids = set(accepted_with_pov(run_dir))
    targets = {t.id: t for t in get_suite("all")}
    steps, skipped = [], []
    for i in sorted(ids):
        t = targets.get(i)
        if t is None or not t.pov_command or not t.build_command:
            skipped.append(f"{i}: no build/PoV command in the target list")
            continue
        p = Path(t.file_path)
        inside = not p.is_absolute() and not p.as_posix().startswith("benchmark_workspace/")
        if not inside:
            skipped.append(f"{i}: sources are not committed to the repository")
            continue
        steps.append(step_for(t))
    header = [f"# Generated by tests/benchmarks/make_ci_workflow.py from run {run_dir.name}.",
              f"# {len(steps)} PoV replay(s). Skipped:"] + [f"#   {s}" for s in skipped or ["(none)"]]
    yml = "\n".join(header) + f"""
name: kavach-pov-replay
on: [push, pull_request]
jobs:
  replay:
    runs-on: macos-14
    steps:
      - uses: actions/checkout@v4
      - name: Toolchain
        run: brew install llvm
""" + "".join(steps)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write(yml)
    print(f"wrote {out}: {len(steps)} replay step(s), {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
