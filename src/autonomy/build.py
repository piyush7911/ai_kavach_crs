"""
Build stage: compile an uploaded repository's sources and one harness into a
sanitized libFuzzer binary.

The build is a generated shell SCRIPT, not a Python call, for one reason: the
repair gates must rebuild it against every patched copy of the repository. The
gate runs a command string in a fresh workspace, so the build has to be
expressible as a command, and the script is that command. It is also saved in
the run directory, which makes the exact compilation auditable.

Compile policy
--------------
* ``-O0``. An optimised build inlines the function under test into the harness
  and ASan then attributes the fault to the harness, which makes crash location
  unresolvable (this happened to our own SYN-05 target).
* ``-fsanitize=fuzzer-no-link,address,undefined`` for library objects and
  ``-fsanitize=fuzzer,...`` at link time, with ``-fno-sanitize-recover=all`` so a
  sanitizer report is a hard failure.
* ``-Dmain=kavach_unused_main`` on repository sources, so a library file that
  also defines a ``main`` (a demo, a CLI) cannot collide with the fuzzer's.
* ``-fcommon`` and ``-w``. Legacy C relies on tentative definitions that modern
  clang rejects at link time, and third-party warnings are not ours to triage.

Tolerance
---------
A library file that does not compile in isolation is skipped and reported, not
fatal, because many repositories carry platform-specific files. The file holding
the function under test is the exception: if it does not compile, the build
fails. Skipped files are named in the build output and recorded in the evidence.
"""

import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from src.analysis_engine.fuzzer_manager import FuzzerManager
from src.autonomy import execute

COMPILE_FLAGS = ("-fsanitize=fuzzer-no-link,address,undefined -fno-sanitize-recover=all "
                 "-fno-omit-frame-pointer -g -O0 -fcommon -w")
LINK_FLAGS = "-fsanitize=fuzzer,address,undefined -fno-sanitize-recover=all -g"

_SKIPPED = re.compile(r"kavach: skipped (\S+)")


class BuildError(RuntimeError):
    """The build could not even be attempted (for example no fuzzer-capable compiler)."""


def fuzz_clang() -> str:
    path = FuzzerManager.libfuzzer_clang()
    if not path:
        raise BuildError(
            "no clang with a libFuzzer runtime was found. Apple's clang does not ship one; "
            "install Homebrew LLVM (`brew install llvm`)")
    return path


def _include_args(dirs: list[str]) -> str:
    out = ['-I"$ROOT"']
    out += ['-I"$ROOT"/' + shlex.quote(d) for d in dirs if d not in (".", "")]
    return " ".join(out)


def render_script(*, clang: str, sources: list[str], include_dirs: list[str], defines: list[str],
                  harness: Path, target_file: str, extra_link: str = "-lm") -> str:
    """The build script text. Arguments: ``ROOT`` (repository copy) and ``OUT`` (binary)."""
    defs = " ".join(shlex.quote("-D" + d) for d in defines)
    inc = _include_args(include_dirs)
    files = " ".join(shlex.quote(s) for s in sources)
    return f'''#!/bin/sh
# Generated by AI Kavach autonomous mode. Do not edit; regenerate instead.
# Object files are linked through a quoted directory and a glob, never through a
# space-separated variable: a path containing a space would split mid-path.
#   usage: kavach_build.sh <repository-root> <output-binary>
ROOT="$1"
OUT="$2"
if [ -z "$ROOT" ] || [ -z "$OUT" ]; then echo "usage: $0 <root> <out>" >&2; exit 2; fi
CC={shlex.quote(clang)}
# KAVACH_COVERAGE=1 adds LLVM source-based coverage, used only by the reach judge.
COV=""; if [ -n "$KAVACH_COVERAGE" ]; then COV="-fprofile-instr-generate -fcoverage-mapping"; fi
OBJ="$(mktemp -d "${{TMPDIR:-/tmp}}/kavach_obj.XXXXXX")" || exit 1
n=0; tobj=""
for f in {files}; do
  n=$((n+1))
  if "$CC" {COMPILE_FLAGS} $COV -Dmain=kavach_unused_main_$n {defs} {inc} -c "$ROOT/$f" -o "$OBJ/$n.o" 2>"$OBJ/$n.err"; then
    if [ "$f" = {shlex.quote(target_file)} ]; then tobj="$OBJ/$n.o"; fi
  elif [ "$f" = {shlex.quote(target_file)} ]; then
    cat "$OBJ/$n.err" >&2
    echo "BUILD FAILED: the file under test ($f) does not compile" >&2
    exit 1
  else
    echo "kavach: skipped $f (does not compile in isolation)" >&2
  fi
done
"$CC" {COMPILE_FLAGS} $COV {defs} {inc} -c {shlex.quote(str(harness))} -o "$OBJ/harness.o" || {{ echo "BUILD FAILED: harness does not compile" >&2; exit 1; }}
if ! "$CC" {LINK_FLAGS} $COV "$OBJ/harness.o" "$OBJ"/[0-9]*.o {extra_link} -o "$OUT" 2>"$OBJ/link.err"; then
  # Some trees are a directory of independent programs, or carry duplicate
  # definitions across files. Fall back to the file under test alone, and say so.
  if [ -n "$tobj" ] && "$CC" {LINK_FLAGS} $COV "$OBJ/harness.o" "$tobj" {extra_link} -o "$OUT" 2>"$OBJ/link2.err"; then
    echo "kavach: full link failed; linked the file under test only" >&2
  else
    cat "$OBJ/link.err" >&2
    echo "BUILD FAILED: link" >&2
    exit 1
  fi
fi
# On macOS the debug info stays in the object files, which are deleted below. Without
# a dSYM every crash frame loses its file:line and triage cannot locate the bug.
if command -v dsymutil >/dev/null 2>&1; then dsymutil "$OUT" >/dev/null 2>&1; fi
rm -rf "$OBJ"
'''


def write_script(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(0o755)
    return path


@dataclass
class BuildOutcome:
    ok: bool
    binary: Optional[Path] = None
    skipped_files: list[str] = field(default_factory=list)
    error: str = ""
    seconds: float = 0.0
    backend: str = ""
    note: str = ""

    def to_dict(self) -> dict:
        return {"ok": self.ok, "binary": str(self.binary) if self.binary else "",
                "skipped_files": self.skipped_files, "error": self.error,
                "seconds": self.seconds, "backend": self.backend, "note": self.note}


def build(script: Path, root: Path, out: Path, workdir: Path, timeout: int = 300,
          env: Optional[dict] = None) -> BuildOutcome:
    """Run the build script on `root`, writing `out`, with `workdir` as the writable workspace."""
    out.parent.mkdir(parents=True, exist_ok=True)
    # The sandbox confines writes to `workdir`. An output elsewhere would fail deep
    # inside the linker as "Operation not permitted", which reads like a sandbox
    # bug rather than a caller mistake, so refuse it here with the real reason.
    try:
        out.resolve().relative_to(workdir.resolve())
    except ValueError:
        raise ValueError(f"output {out} must be inside the workspace {workdir}: writes are "
                         "confined to the workspace by the sandbox")
    cmd = f'sh {shlex.quote(str(script))} {shlex.quote(str(root))} {shlex.quote(str(out))}'
    r = execute.run(cmd, workdir, timeout=timeout, env=env)
    if not r.ran:
        return BuildOutcome(ok=False, error=r.note, backend=r.backend, note=r.note)
    skipped = _SKIPPED.findall(r.stderr)
    if r.ok and out.exists():
        return BuildOutcome(ok=True, binary=out, skipped_files=skipped, seconds=r.seconds,
                            backend=r.backend, note=r.note)
    tail = "\n".join(r.stderr.strip().splitlines()[-12:])
    if r.timed_out:
        tail = f"build timed out after {timeout}s\n" + tail
    return BuildOutcome(ok=False, skipped_files=skipped, error=tail or "build failed with no output",
                        seconds=r.seconds, backend=r.backend, note=r.note)


def prepare(prepare_command: str, root: Path, timeout: int = 300) -> execute.ExecResult:
    """Run the one-time preparation (`./configure`, `cmake -S .`) inside the snapshot, sandboxed."""
    return execute.run(prepare_command, root, timeout=timeout)
